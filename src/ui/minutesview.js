/* Minutes (PRD-meetings US-07): the Summarise call to action under the
   transcript with its running / failed / offline states and the one-time
   disclosure (AC-05.6), then the Minutes block: Summary, Decisions, Open
   questions, each editable in place, the "Generated by AI" line, the
   stale chip and Regenerate. Action cards are Phase 17; until then the
   block ends with a count. */

import { S, minutesStale, editMinutes, markDisclosed, meetingTitle, priorityName } from '../store.js';
import { toast } from './primitives.js';
import { fmtDate, fmtClock } from '../dates.js';
import { esc } from '../util.js';
import { icon } from './icons.js';
import { confirmDialog } from './primitives.js';
