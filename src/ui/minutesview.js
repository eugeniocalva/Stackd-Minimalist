import { aiButtonState, openPlanRequired, openAllowanceUsed } from './paywall.js';

export const DISCLOSURE = 'The transcript, with the speaker names you gave, is sent to our server and to an AI model provider to write the minutes and find the actions. Nothing is kept there after the result comes back, and nothing is sent until you press this button.';

/* ── Call to action (AC-06.7, AC-07.1, AC-05.4, AC-05.5) ─────────────── */

export function summariseCtaHTML(m) {
  if (!m.transcript) return '';
  const running = m.jobs?.summarise || isRunning(m.id, 'summarise');
  const err = m.lastError?.step === 'summarise' ? m.lastError : null;
  const offline = !isOnline();
  const stale = minutesStale(m);
  if (running) {
    return `
    <div class="cta cta-running" role="status" aria-live="polite">
      <span class="spin" aria-hidden="true"></span>
      <span>Summarising…</span>
      <span class="hint">keeps going if you leave this screen</span>
    </div>`;
  }
  const state = aiButtonState('summarise');
  const planErr = err && (err.code === 'plan_required' || err.code === 'allowance_exhausted');
  const label = err && !planErr ? 'Retry' : m.minutes ? 'Regenerate' : 'Summarise into minutes and actions';
  return `
  <div class="cta" data-cta="summarise">
    ${err && !planErr ? `<div class="notice"><span>${esc(err.message)}</span></div>` : ''}
    ${err?.code === 'allowance_exhausted' ? `<div class="notice"><span>${esc(err.message)}</span><button type="button" class="btn btn-sm btn-ghost" data-plan-sheet="allowance_exhausted">Upgrade</button></div>` : ''}
    <span class="cta-row">
      <button type="button" class="btn ${m.minutes ? 'btn-secondary' : 'btn-primary'} ${state.locked ? 'is-locked' : ''}" data-summarise ${offline ? 'disabled' : ''} ${state.locked ? 'data-locked="1"' : ''}>
        ${icon(state.locked ? 'lock' : 'sparkle', 18)}${label}
      </button>
      ${state.hint ? `<span class="hint cta-hint">${esc(state.hint)}</span>` : ''}
    </span>
    ${stale && m.minutes ? '<span class="tag tag-soon">Transcript edited since</span>' : ''}
    ${offline ? '<span class="hint">Needs a connection</span>' : ''}
  </div>`;
}

export function bindSummariseCta(root, m) {
  root.querySelector('[data-plan-sheet]')?.addEventListener('click', () =>
    openAllowanceUsed({ step: 'summarise', resetsAt: m.lastError?.resetsAt || null }));
  root.querySelector('[data-summarise]')?.addEventListener('click', async (e) => {
    if (e.currentTarget.dataset.locked) { openPlanRequired({ step: 'summarise' }); return; }   // Free: the paywall, no request (AC-12.6)
    if (!S.ai.disclosed) {
      if (!await confirmDialog('Before the first summary', DISCLOSURE, { confirmLabel: 'Continue' })) return;
      markDisclosed();
    }
    if (m.minutes && !await confirmDialog('Regenerate the minutes?', 'The minutes and the actions not yet added to a board are replaced.', { confirmLabel: 'Regenerate' })) return;
    summarise(m.id);
  });
}

/** Plain-text minutes for the clipboard (Should: Copy minutes). */
export function minutesToText(m) {
  const mm = m.minutes;
  const lines = [meetingTitle(m), `${fmtDate(m.createdAt, S.dateFormat)} ${fmtClock(m.createdAt)}`, ''];
  lines.push('Summary', mm.summary || 'None noted', '');
  lines.push('Decisions', ...(mm.decisions.length ? mm.decisions.map((d) => `- ${d}`) : ['None noted']), '');
  lines.push('Open questions', ...(mm.openQuestions.length ? mm.openQuestions.map((q) => `- ${q}`) : ['None noted']), '');
  const actions = m.actions.filter((a) => a.status !== 'dismissed');
  lines.push('Actions', ...(actions.length ? actions.map((a) => `- ${a.title}${a.due ? ` · due ${fmtDate(a.due, S.dateFormat)}` : ''}${a.priority !== 'none' ? ` · ${priorityName(a.priority)}` : ''}${a.status === 'added' ? ' · on a board' : ''}`) : ['None']));
  lines.push('', generatedLine(mm));
  return lines.join('\n');
}

/* ── Minutes block (AC-07.2 – AC-07.5) ───────────────────────────────── */

const generatedLine = (mm) => `Generated by AI · ${fmtDate(mm.generatedAt, S.dateFormat)} ${fmtClock(mm.generatedAt)} · check before you rely on it.`;

function sectionHTML(key, title, value, { readOnly, list }) {
  const text = list ? value.join('\n') : value;
  const empty = !text.trim();
  if (readOnly) {
    return `
    <div class="min-section">
      <span class="section-title">${title}</span>
      ${empty ? '<p class="min-empty">None noted</p>'
        : list ? `<ul class="min-list">${value.map((x) => `<li>${esc(x)}</li>`).join('')}</ul>` : `<p class="min-text">${esc(text)}</p>`}
    </div>`;
  }
  return `
  <div class="min-section">
    <label class="section-title" for="min-${key}">${title}</label>
    <textarea id="min-${key}" class="min-edit ${list ? 'min-edit-list' : ''}" data-min="${key}" rows="1" placeholder="None noted" aria-label="${title}">${esc(text)}</textarea>
    ${list ? '<span class="hint">One per line</span>' : ''}
  </div>`;
}

export function minutesHTML(m, { readOnly = false } = {}) {
  const mm = m.minutes;
  if (!mm) return '';
  return `
  <section class="mblock" data-block="minutes" aria-label="Minutes">
    <div class="mblock-head">
      <span class="section-title">Minutes</span>
      <span class="hint">${esc(generatedLine(mm))}</span>
      <span class="mblock-actions"><button type="button" class="btn btn-ghost btn-sm" data-copy-minutes>${icon('copy', 16)}Copy</button></span>
    </div>
    <div class="card minutes">
      ${sectionHTML('summary', 'Summary', mm.summary, { readOnly, list: false })}
      ${sectionHTML('decisions', 'Decisions', mm.decisions, { readOnly, list: true })}
      ${sectionHTML('openQuestions', 'Open questions', mm.openQuestions, { readOnly, list: true })}
    </div>
  </section>`;
}

const grow = (ta) => { ta.style.height = 'auto'; ta.style.height = `${ta.scrollHeight}px`; };

export function bindMinutes(root, m, { readOnly = false } = {}) {
  root.querySelector('[data-copy-minutes]')?.addEventListener('click', async () => {
    try { await navigator.clipboard.writeText(minutesToText(m)); toast('Minutes copied'); }
    catch { toast("Couldn't copy on this device"); }
  });
  if (readOnly) return;
  let timer = null;
  const pending = {};
  const flush = () => {
    if (!timer) return;
    clearTimeout(timer); timer = null;
    editMinutes(m.id, { ...pending });
    Object.keys(pending).forEach((k) => delete pending[k]);
  };
  root.querySelectorAll('[data-min]').forEach((ta) => {
    grow(ta);
    ta.addEventListener('input', () => {
      grow(ta);
      const key = ta.dataset.min;
      pending[key] = key === 'summary' ? ta.value : ta.value.split('\n').map((s) => s.trim()).filter(Boolean);
      clearTimeout(timer); timer = setTimeout(flush, 500);
    });
    ta.addEventListener('blur', flush);
  });
  window.addEventListener('pagehide', flush, { once: true });
}

/** Re-grow after a re-render that restored the textareas' text. */
export function layoutMinutes(root) { root.querySelectorAll('[data-min]').forEach(grow); }
