/* Shared by scripts/bundle.mjs (writes app.bundle.js) and
   scripts/check-bundle.mjs (compares it): builds the whole app (app.js and
   everything it imports from src/) as one classic script, in memory.

   index.html loads app.bundle.js only when the page is opened straight from
   disk (file://), where browsers refuse ES modules; the website, the local
   server and the iOS app keep loading the modules. esbuild output is
   deterministic for the same inputs and version (pinned in package-lock). */
import { build } from 'esbuild';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const BUNDLE = resolve(ROOT, 'app.bundle.js');

const BANNER = `/* GENERATED by scripts/bundle.mjs from app.js and src/. Do not edit.
   Loaded only when index.html is opened from disk (file://), where browsers
   block ES modules. Rebuild with: npm run bundle */`;

/** The bundle's text, built in memory. */
export async function bundleSource() {
  const result = await build({
    absWorkingDir: ROOT,
    entryPoints: ['app.js'],
    bundle: true,
    format: 'iife',
    write: false,
    charset: 'utf8',
    legalComments: 'none',
    banner: { js: BANNER },
    logLevel: 'silent',
  });
  return result.outputFiles[0].text;
}
